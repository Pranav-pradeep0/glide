import React, { useMemo } from 'react';
import { ScrollView, StyleSheet, Text, View } from 'react-native';
import { useTheme } from '@/hooks/useTheme';
import { metrics, type } from '@/theme/theme';

/**
 * Release notes come from the GitHub release body, which the release workflow builds
 * from commit subjects and then appends a build-info footer to. Both the update modal
 * and the Settings update card show the same thing, so they share one renderer.
 */
export function formatNotes(notes: string | null): string {
    if (!notes) {return 'No changelog provided.';}

    let normalized = notes
        .replace(/\r\n/g, '\n')
        .replace(/\\r\\n/g, '\n')
        .replace(/\\n/g, '\n')
        .replace(/\\r/g, '\n')
        .trim();

    const dividerIndex = normalized.indexOf('\n---');
    if (dividerIndex !== -1) {
        normalized = normalized.slice(0, dividerIndex).trim();
    }

    const buildInfoIndex = normalized.indexOf('\n**Build Info**');
    if (buildInfoIndex !== -1) {
        normalized = normalized.slice(0, buildInfoIndex).trim();
    }

    return normalized.length > 0 ? normalized : 'No changelog provided.';
}

export interface NotesLine {
    kind: 'heading' | 'bullet' | 'text';
    text: string;
}

/**
 * The notes are generated by the release workflow, so the Markdown in them is exactly
 * three shapes: `### Features`, `- a change`, and the odd plain line. A full Markdown
 * engine for that was `react-native-markdown-display`, abandoned since 2021 and pulling
 * markdown-it 10 with it.
 */
export function parseNotes(notes: string): NotesLine[] {
    return notes
        .split('\n')
        .map((raw) => raw.trim())
        .filter((line) => line.length > 0)
        .map((line) => {
            const heading = line.match(/^#{1,6}\s+(.*)$/);
            if (heading) {return { kind: 'heading' as const, text: strip(heading[1]) };}

            const bullet = line.match(/^[-*+]\s+(.*)$/);
            if (bullet) {return { kind: 'bullet' as const, text: strip(bullet[1]) };}

            return { kind: 'text' as const, text: strip(line) };
        });
}

/** Emphasis markers, which there is nothing to render them as here, and link syntax. */
function strip(text: string): string {
    return text
        .replace(/\[([^\]]*)\]\([^)]*\)/g, '$1')
        .replace(/(\*\*|__|\*|_|`)/g, '')
        .trim();
}

interface UpdateNotesProps {
    notes: string | null;
    maxHeight?: number;
}

export function UpdateNotes({ notes, maxHeight = 200 }: UpdateNotesProps) {
    const { colors } = useTheme();
    const lines = useMemo(() => parseNotes(formatNotes(notes)), [notes]);

    return (
        <View style={styles.block}>
            <Text style={[type.heading, styles.title, { color: colors.text }]}>What's new</Text>
            <ScrollView style={{ maxHeight }} showsVerticalScrollIndicator={false} nestedScrollEnabled>
                {lines.map((line, index) => {
                    if (line.kind === 'heading') {
                        return (
                            <Text key={index} style={[type.heading, styles.lineHeading, { color: colors.text }]}>
                                {line.text}
                            </Text>
                        );
                    }
                    if (line.kind === 'bullet') {
                        return (
                            <View key={index} style={styles.bulletRow}>
                                <Text style={[type.body, styles.body, { color: colors.textSecondary }]}>•</Text>
                                <Text style={[type.body, styles.body, styles.bulletText, { color: colors.textSecondary }]}>
                                    {line.text}
                                </Text>
                            </View>
                        );
                    }
                    return (
                        <Text key={index} style={[type.body, styles.body, styles.paragraph, { color: colors.textSecondary }]}>
                            {line.text}
                        </Text>
                    );
                })}
            </ScrollView>
        </View>
    );
}

const styles = StyleSheet.create({
    block: { marginBottom: metrics.space.lg },
    title: { marginBottom: metrics.space.sm },
    lineHeading: { marginTop: metrics.space.sm, marginBottom: metrics.space.xs },
    body: { lineHeight: 20 },
    paragraph: { marginBottom: metrics.space.xs },
    bulletRow: { flexDirection: 'row', gap: metrics.space.sm, marginBottom: metrics.space.xs },
    bulletText: { flex: 1 },
});
